export function installWhyPage({document=globalThis.document}={}){
  const get=id=>document.getElementById(id);
  const help=get('settingsHelpCard'),why=get('whyScreen');
  if(!help||!why)return {apply(){}};
  function apply(language){
    const t=WHY_COPY[language]||WHY_COPY.en;
    help.querySelector('h2').textContent=t.help;
    get('whyMitsukotobaButton').textContent=t.whyButton;
    get('tutorialReplayButton').textContent=t.tutorial;
    get('whyBackButton').textContent=t.back;
    get('whyTitle').textContent=t.title;
    for(let i=0;i<3;i++)get('whyIntro'+(i+1)).textContent=t.intro[i];
    // Preserve a visible emphasis on the actual purpose, not a proven outcome.
    get('whyIntro4').querySelector('strong').textContent=t.intro[3];
    get('whyCaution').textContent=t.caution;
    get('whyResearchLabel').textContent=t.links[0];
    get('whyTopicLabel').textContent=t.links[1];
    get('whyVisualCueLabel').textContent=t.links[2];
    get('whyTopicLink').href='./topic-guide.html?lang='+encodeURIComponent(language);
    // Dev-only gallery: opened by the app button, not a static production link.
    why.querySelector('nav').setAttribute('aria-label',t.more);
    why.querySelector('.about-characters').setAttribute('aria-label',t.people);
  }
  return {apply};
}
